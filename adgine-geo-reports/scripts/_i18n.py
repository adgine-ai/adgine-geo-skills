def normalize_locale(value, *hints):
    """Normalize supported locale aliases; ``auto`` inspects supplied text hints."""
    raw = str(value or "auto").strip().lower().replace("_", "-")
    if raw not in ("", "auto"):
        if raw == "zh" or raw.startswith("zh-"):
            return "zh-CN"
        if raw == "en" or raw.startswith("en-"):
            return "en-US"
        return DEFAULT_LOCALE
    for hint in hints:
        if hint and re.search(r"[\u3400-\u4dbf\u4e00-\u9fff]", str(hint)):
            return "zh-CN"
    return DEFAULT_LOCALE


def is_zh(locale):
    return normalize_locale(locale) == "zh-CN"


def t(locale, key, **values):
    resolved = normalize_locale(locale)
    template = TEXT.get(resolved, TEXT[DEFAULT_LOCALE]).get(key)
    if template is None:
        template = TEXT[DEFAULT_LOCALE].get(key, key)
    return template.format(**values) if values else template


def label(key, locale="en-US"):
    """Create a stable display label from a snake/kebab-case API field."""
    raw = str(key or "")
    normalized = raw.replace("-", "_").lower()
    if is_zh(locale):
        if normalized in LABELS_ZH:
            return LABELS_ZH[normalized]
        parts = normalized.split("_")
        translated = [TOKENS_ZH.get(part) for part in parts]
        if any(item is not None for item in translated):
            return "".join(item if item is not None else part.capitalize() for part, item in zip(parts, translated))
    elif normalized in LABELS_EN:
        return LABELS_EN[normalized]
    special = {
        "ai": "AI", "ga4": "GA4", "sov": "Share of Voice", "avg": "Average",
        "pct": "%", "kpi": "KPI", "url": "URL", "utm": "UTM",
    }
    return " ".join(special.get(part.lower(), part.capitalize()) for part in raw.replace("-", "_").split("_"))


def localize_unit(value, locale="en-US"):
    if value is None or not is_zh(locale):
        return value
    raw = str(value)
    if raw in UNITS_ZH:
        return UNITS_ZH[raw]
    return UNITS_ZH.get(raw.lower(), raw)


def status_label(value, locale="en-US"):
    raw = str(value or "ok")
    return STATUS_ZH.get(raw.lower(), raw) if is_zh(locale) else raw
